using System.Text;

namespace PlaywrightTestStudio;

/// <summary>
/// Writes the C# file for a link. One link, one file, one [Test] method per
/// test case recorded against it - so the file is a readable NUnit + Playwright
/// fixture you can run from Visual Studio or CI, not a dump of JSON.
/// </summary>
internal static class CodeGen
{
    /// <summary>
    /// Regenerates the file that covers <paramref name="url"/> from every test
    /// case saved against that link. Returns the file path.
    /// </summary>
    public static string WriteForLink(ProjectStore store, string url, IReadOnlyList<TestCase> testsForLink)
    {
        Directory.CreateDirectory(store.CodeDir);

        var className = ClassNameFor(url);
        var file = Path.Combine(store.CodeDir, className + ".cs");
        var sb = new StringBuilder();

        sb.AppendLine("// ---------------------------------------------------------------------------");
        sb.AppendLine("// Generated by Playwright Test Studio. Regenerated whenever a test case for");
        sb.AppendLine("// this link is saved, so hand edits here are overwritten.");
        sb.AppendLine($"// Link    : {url}");
        sb.AppendLine($"// Project : {store.Name}");
        sb.AppendLine($"// Written : {DateTime.Now:yyyy-MM-dd HH:mm}");
        sb.AppendLine("// ---------------------------------------------------------------------------");
        sb.AppendLine();
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine("using Microsoft.Playwright;");
        sb.AppendLine("using Microsoft.Playwright.NUnit;");
        sb.AppendLine("using NUnit.Framework;");
        sb.AppendLine();
        sb.AppendLine($"namespace PlaywrightTestStudio.Generated.{Storage.Identifier(store.Name)};");
        sb.AppendLine();
        sb.AppendLine("[TestFixture]");
        sb.AppendLine("[Parallelizable(ParallelScope.Self)]");
        sb.AppendLine($"public class {className} : PageTest");
        sb.AppendLine("{");
        sb.AppendLine($"    private const string Url = {Literal(url)};");

        var usedNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        foreach (var test in testsForLink.OrderBy(t => t.CreatedUtc))
        {
            sb.AppendLine();
            AppendTestMethod(sb, test, usedNames);
        }

        sb.AppendLine("}");

        File.WriteAllText(file, sb.ToString());
        WriteReadme();

        return file;
    }

    private static void AppendTestMethod(StringBuilder sb, TestCase test, HashSet<string> usedNames)
    {
        var method = UniqueMethodName(test, usedNames);

        sb.AppendLine("    /// <summary>");
        sb.AppendLine($"    /// {Comment(test.Name)}");

        if (test.LastResult is not null)
        {
            sb.AppendLine($"    /// Last run in the studio: {test.LastResult.Status} " +
                          $"({test.LastResult.RanUtc:yyyy-MM-dd HH:mm} UTC)");
        }

        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    [Test]");
        sb.AppendLine($"    public async Task {method}()");
        sb.AppendLine("    {");
        sb.AppendLine("        await Page.GotoAsync(Url);");

        var fields = test.Fields.Where(f => f.Use).ToList();

        if (fields.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("        // Data entered on the form");

            foreach (var field in fields)
            {
                sb.AppendLine($"        {FieldStatement(field)}   // {Comment(field.Label)}");
            }
        }

        if (test.Clicks.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("        // Buttons pressed, in order");

            foreach (var click in test.Clicks)
            {
                sb.AppendLine($"        await Page.ClickAsync({Literal(click.Selector)});   // {Comment(click.Label)}");

                if (click.WaitAfter)
                {
                    sb.AppendLine("        await Page.WaitForLoadStateAsync(LoadState.NetworkIdle);");
                }
            }
        }

        sb.AppendLine();
        sb.AppendLine("        // Assertions");

        if (test.Assertions.Count == 0)
        {
            sb.AppendLine("        Assert.Fail(\"No assertion was recorded for this test case.\");");
        }
        else
        {
            foreach (var assertion in test.Assertions)
            {
                foreach (var line in AssertionStatements(assertion))
                {
                    sb.AppendLine($"        {line}");
                }
            }
        }

        sb.AppendLine("    }");
    }

    private static string FieldStatement(FieldValue field) => field.Kind switch
    {
        "select" => $"await Page.SelectOptionAsync({Literal(field.Selector)}, " +
                    $"new SelectOptionValue {{ Label = {Literal(field.Value)} }});",

        "radio" => $"await Page.CheckAsync({Literal(field.Selector)});",

        "checkbox" => $"await Page.SetCheckedAsync({Literal(field.Selector)}, " +
                      $"{(Runner.IsTruthy(field.Value) ? "true" : "false")});",

        _ => $"await Page.FillAsync({Literal(field.Selector)}, {Literal(field.Value)});"
    };

    private static IEnumerable<string> AssertionStatements(AssertionSpec spec)
    {
        switch (spec.Kind)
        {
            case AssertionKinds.UrlContains:
                yield return $"Assert.That(Page.Url, Does.Contain({Literal(spec.Expected)}).IgnoreCase);";
                break;

            case AssertionKinds.TitleContains:
                yield return $"Assert.That(await Page.TitleAsync(), Does.Contain({Literal(spec.Expected)}).IgnoreCase);";
                break;

            case AssertionKinds.PageTextContains:
                yield return $"Assert.That(await Page.InnerTextAsync(\"body\"), Does.Contain({Literal(spec.Expected)}).IgnoreCase);";
                break;

            case AssertionKinds.PageTextNotContains:
                yield return $"Assert.That(await Page.InnerTextAsync(\"body\"), Does.Not.Contain({Literal(spec.Expected)}).IgnoreCase);";
                break;

            case AssertionKinds.ElementVisible:
                yield return $"await Expect(Page.Locator({Literal(spec.Selector)}).First).ToBeVisibleAsync();";
                break;

            case AssertionKinds.ElementNotVisible:
                yield return $"await Expect(Page.Locator({Literal(spec.Selector)}).First).ToBeHiddenAsync();";
                break;

            case AssertionKinds.ElementTextContains:
                yield return $"await Expect(Page.Locator({Literal(spec.Selector)}).First)" +
                             $".ToContainTextAsync({Literal(spec.Expected)});";
                break;

            case AssertionKinds.ElementValueEquals:
                yield return $"await Expect(Page.Locator({Literal(spec.Selector)}).First)" +
                             $".ToHaveValueAsync({Literal(spec.Expected)});";
                break;

            case AssertionKinds.ElementEnabled:
                yield return $"await Expect(Page.Locator({Literal(spec.Selector)}).First).ToBeEnabledAsync();";
                break;

            case AssertionKinds.ElementChecked:
                yield return $"await Expect(Page.Locator({Literal(spec.Selector)}).First).ToBeCheckedAsync();";
                break;

            default:
                yield return $"Assert.Fail({Literal($"Unknown assertion kind: {spec.Kind}")});";
                break;
        }
    }

    /// <summary>A class name derived from the link, e.g. portal_uind_RightsPage.</summary>
    public static string ClassNameFor(string url)
    {
        string host;
        string path;

        try
        {
            var uri = new Uri(url);
            host = uri.Host.Replace("www.", "");
            path = uri.AbsolutePath;
        }
        catch (UriFormatException)
        {
            host = url;
            path = "";
        }

        var name = Storage.Identifier(host + "_" + path);

        return name.Length > 70 ? name[..70] + "Tests" : name + "Tests";
    }

    private static string UniqueMethodName(TestCase test, HashSet<string> used)
    {
        var baseName = Storage.Identifier(string.IsNullOrWhiteSpace(test.Name) ? "TestCase" : test.Name);

        if (baseName.Length > 60)
        {
            baseName = baseName[..60];
        }

        var name = baseName;
        var n = 2;

        while (!used.Add(name))
        {
            name = $"{baseName}_{n++}";
        }

        return name;
    }

    /// <summary>A C# string literal, quotes and backslashes escaped.</summary>
    private static string Literal(string value)
    {
        var escaped = value
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"")
            .Replace("\r", "\\r")
            .Replace("\n", "\\n");

        return "\"" + escaped + "\"";
    }

    /// <summary>Text safe to drop into a // comment.</summary>
    private static string Comment(string value) =>
        value.Replace("\r", " ").Replace("\n", " ").Trim();

    /// <summary>
    /// Explains, once, how to compile the generated files - they need NUnit,
    /// which this app deliberately does not reference.
    /// </summary>
    private static void WriteReadme()
    {
        var file = Path.Combine(Storage.CodeRoot, "README.md");

        if (File.Exists(file))
        {
            return;
        }

        Directory.CreateDirectory(Storage.CodeRoot);

        File.WriteAllText(file, """
        # Generated tests

        Playwright Test Studio writes one C# file per link here, grouped into a
        folder per studio project. They are NUnit fixtures, and they are **not**
        compiled by `PlaywrightTestStudio.csproj` (see the `Compile Remove` item
        in that file) because this app does not reference NUnit.

        To run them, create a test project once and point it at this folder:

            dotnet new nunit -n GeneratedTests.Runner
            cd GeneratedTests.Runner
            dotnet add package Microsoft.Playwright.NUnit
            dotnet build

        Then add to `GeneratedTests.Runner.csproj`:

            <ItemGroup>
              <Compile Include="..\<ProjectFolder>\**\*.cs" />
            </ItemGroup>

        and run:

            dotnet test

        Note that these fixtures use a fresh browser context, so any link behind
        a login needs a storage-state file or a sign-in step added to the
        fixture. Inside the studio itself the shared browser profile handles it.
        """);
    }
}
